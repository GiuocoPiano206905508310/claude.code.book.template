/// 社労士実務（労働法令・労働保険・社会保険・年金・給与計算・助成金・
/// 人事労務管理）の分野を示すキーワード。
///
/// 厚生労働省の「新着情報」は医療・医薬品・公衆衛生・福祉・研究規制等を含む
/// 省全体の一覧のため、これまでのように「無関係な分野」を除外語で列挙する
/// 方式では、新しい分野の記事（実例:「ヒトゲノム編集胚等の取扱いの規制に
/// ついて」）を防ぎきれなかった。そこで省全体の一覧から取り込む記事は、
/// タイトルがこれらの語のいずれかを含むものに限る（含む場合も、AIが
/// 社労士実務に直結しないと判定すれば除外する）。
final _practiceKeywordPattern = RegExp(
  // 労働条件・労務管理
  r'労働|労務|労使|雇用|雇入|賃金|給与|賞与|退職|解雇|採用|求人|求職|就業|就労|勤務'
  r'|働き方|働く|休暇|休業|休日|有給|年休|残業|時間外|シフト|副業|兼業|テレワーク'
  r'|ハラスメント|パワハラ|セクハラ|カスハラ|育児|介護離職|両立支援|女性活躍|男女|均等'
  r'|同一労働|無期転換|派遣|請負|フリーランス|障害者雇用|高年齢者|外国人(労働|雇用)'
  r'|技能実習|育成就労|特定技能|人材開発|職業訓練|職業能力|キャリアアップ'
  // 安全衛生・労災
  r'|安全衛生|労災|過労|メンタルヘルス|ストレスチェック|産業医|熱中症'
  // 社会保険・年金
  r'|社会保険|健康保険|厚生年金|国民年金|年金|協会けんぽ|保険料|標準報酬|算定基礎'
  r'|被保険者|被扶養者|適用拡大|短時間労働者|出産手当|傷病手当|子ども・子育て支援金'
  // 給与計算・手続き・助成金
  r'|源泉|年末調整|電子申請|届書|助成金|奨励金|給付金|最低賃金'
  r'|社会保険労務士|事業主',
);

// 「厚生労働大臣」「厚生労働省」等の省名に含まれる「労働」で、医療・
// 福祉分野の記事（大臣表彰・記者会見のお知らせ等）が通らないようにする。
final _ministryName = RegExp('厚生労働');

/// [title]が社労士実務の分野のキーワードを含むかどうか。
bool isPracticeRelatedTitle(String title) =>
    _practiceKeywordPattern.hasMatch(title.replaceAll(_ministryName, ''));
