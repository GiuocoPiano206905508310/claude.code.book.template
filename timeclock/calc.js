// 時給換算 = 基本給 ÷ 月平均所定労働時間
function calcHourlyWage(baseSalary, monthlyStandardHours) {
  return baseSalary / (monthlyStandardHours || 160);
}

// 欠勤控除 = 日給換算（基本給 ÷ 月平均所定労働日数） × 欠勤日数
function calcAbsenceDeduction(baseSalary, monthlyStandardDays, absenceDays) {
  if (!absenceDays) return 0;
  const daily = baseSalary / (monthlyStandardDays || 20);
  return Math.round(daily * absenceDays);
}

// ----------------------------------------------------------------------
// 年齢・年齢区分ヘルパー（日本時間基準でリアルタイムに算定）
// ----------------------------------------------------------------------
// 実行環境のタイムゾーンに関わらず「日本時間の現在日時」を取得する。
// toLocaleString()の出力を再度Dateに文字列パースさせる方式は、パース結果が
// 実装依存（ブラウザ間で非互換）でSafari等では正しく動かないことがあるため、
// Intl.DateTimeFormatで日本時間の各フィールドを取得し、数値から組み立てる。
function getJstNow() {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone: 'Asia/Tokyo',
    year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
    hour12: false,
  }).formatToParts(new Date());
  const get = (type) => Number(parts.find((p) => p.type === type).value);
  const year = get('year');
  const month = get('month');
  const day = get('day');
  const hour = get('hour') % 24; // 一部の実装で深夜0時が"24"として返るための補正
  const minute = get('minute');
  const second = get('second');
  return new Date(year, month - 1, day, hour, minute, second);
}

// birthDate: 'YYYY-MM-DD' / asOfDate: 基準日（省略時は日本時間の現在日時）
function calcAge(birthDate, asOfDate) {
  if (!birthDate) return null;
  const parts = birthDate.split('-').map(Number);
  if (parts.length !== 3 || parts.some((n) => Number.isNaN(n))) return null;
  const [by, bm, bd] = parts;
  const asOf = asOfDate || getJstNow();
  let age = asOf.getFullYear() - by;
  const hadBirthdayThisYear = (asOf.getMonth() + 1 > bm) || (asOf.getMonth() + 1 === bm && asOf.getDate() >= bd);
  if (!hadBirthdayThisYear) age--;
  return Math.max(0, age);
}

// 'YYYY-MM-DD' 形式に整形する
function formatDateYmd(date) {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
}

